TREND = [1.07, 1.05, 1.08, 1.04, 1.03, 1.02, 1.01]  # older months were a bit pricier

def load_listings():
    out = []
    for key, cat, brand, ram, spec, rating, titles, prices, reviews in CATALOGUE:
        rng = random.Random(key)
        for i, (market, price) in enumerate(prices.items()):
            hist = [round(price * t * rng.uniform(0.98, 1.02)) for t in TREND] + [price]
            out.append(dict(id=f"{key}-{market}", marketplace=market, title=titles[i % 2], brand=brand, cat=cat,
                price=price, rating=round(rating + rng.uniform(-.1, .1), 1),
                rating_count=rng.randint(2000, 15000) if cat == "shoes" else rng.randint(300, 4000),
                ram=ram, spec=spec, reviews=reviews[i::2], history=hist,
                url=f"https://example.com/{market.lower()}/{key}"))
    return out
